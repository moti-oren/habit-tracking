import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import tailwindcss from 'tailwindcss';
import tailwindConfig from './tailwind.config.js';
import cdnPrefixes from './build/cdn-autoprefixer-prefixes.json' with { type: 'json' };

// Two things the Tailwind Play CDN did differently from a normal build, reproduced here so the CSS
// behaves exactly like the original page's:
//
// 1. Rule order among ties. The CDN regenerated its CSS each time new classes appeared in the DOM and
//    appended each batch after the previous ones, so among utilities that tie (same plugin, same
//    variant, e.g. bg-white and bg-indigo-50/40) a class first used by JavaScript came AFTER a class
//    already in the page's markup, and wins when an element has both (e.g. a selected habit card
//    gets its tint). A build sorts each tie alphabetically instead. Here, within every run of tied
//    rules, classes from index.html come first and JS-only classes after; nothing else moves.
//
// 2. Vendor prefixes. The CDN ran autoprefixer on the CSS it generated — never on the page's own
//    styles — with `remove: false` and a prefix table precompiled for its target browsers (mid-2023
//    data), e.g. -webkit-backdrop-filter for the blurred header on Safari / iOS before 18. Only
//    Tailwind's output is prefixed here, with that same table (build/cdn-autoprefixer-prefixes.json,
//    from scripts/extract-cdn-prefixes.mjs). Autoprefixer's classes are used, so its version is pinned.
//
// e2e/visual-parity.spec.js compares the computed style of every element with the original's.
const require = createRequire(import.meta.url);
const Browsers = require('autoprefixer/lib/browsers');
const Prefixes = require('autoprefixer/lib/prefixes');
const { agents } = require('caniuse-lite/dist/unpacker/agents');
const { createContext } = require('tailwindcss/lib/lib/setupContextUtils');
const { generateRules } = require('tailwindcss/lib/lib/generateRules');
const resolveConfig = require('tailwindcss/resolveConfig');

const ROOT = path.dirname(fileURLToPath(import.meta.url));

/** Marker in src/styles/main.css: everything after it is generated by Tailwind. */
export const TAILWIND_MARKER = '@autoprefix-below';

/** The browsers named in the CDN's table: its targets that needed any prefix. */
export const CDN_PREFIX_TARGETS = [...new Set(Object.values(cdnPrefixes).flatMap(e => e.browsers || []))].sort();

const generatedNodes = (root, postcss) => {
    const index = root.nodes.findIndex(n => n.type === 'comment' && n.text.includes(TAILWIND_MARKER));
    if (index === -1) return null;
    const generated = postcss.root();
    for (const node of root.nodes.slice(index + 1)) generated.append(node);
    return generated;
};

/** Classes used in the static markup of index.html (the CDN's first batches). */
function staticClasses() {
    const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
    return new Set([...html.matchAll(/\sclass="([^"]*)"/g)].flatMap(m => m[1].split(/\s+/)).filter(Boolean));
}

function orderTiesLikeTheCdn() {
    const context = createContext(resolveConfig(tailwindConfig));
    const metaCache = new Map(); // class -> Map(normalized selector -> sort meta)
    const norm = s => s.replace(/\s+/g, ' ').trim();
    const metasOf = cls => {
        if (!metaCache.has(cls)) {
            const bySelector = new Map();
            for (const [meta, node] of generateRules(new Set([cls]), context)) {
                const visit = n =>
                    n.type === 'rule' ? bySelector.set(norm(n.selector), meta) : n.each && n.each(visit);
                visit(node);
            }
            metaCache.set(cls, bySelector);
        }
        return metaCache.get(cls);
    };
    const classesIn = selector =>
        [...selector.matchAll(/\.((?:\\.|[^\s.:>+~[\]()#,])+)/g)].map(m => m[1].replace(/\\(.)/g, '$1'));
    const describe = rule => {
        for (const cls of classesIn(rule.selector)) {
            const meta = metasOf(cls).get(norm(rule.selector));
            if (meta) return { cls, meta };
        }
        return null;
    };
    return {
        postcssPlugin: 'tailwind-order-ties-like-the-cdn',
        OnceExit(root, { postcss }) {
            const generated = generatedNodes(root, postcss);
            if (!generated) return;
            const inMarkup = staticClasses();
            const reorder = container => {
                const nodes = container.nodes ? [...container.nodes] : [];
                nodes.forEach(n => n.type === 'atrule' && reorder(n));
                const info = nodes.map(n => (n.type === 'rule' ? describe(n) : null));
                const out = [];
                for (let i = 0; i < nodes.length;) {
                    let j = i + 1;
                    while (
                        j < nodes.length &&
                        info[i] &&
                        info[j] &&
                        context.offsets.compare(info[i].meta, info[j].meta) === 0n
                    )
                        j++;
                    const run = nodes
                        .slice(i, j)
                        .map((n, k) => ({ n, early: !info[i + k] || inMarkup.has(info[i + k].cls) }));
                    out.push(...run.filter(r => r.early).map(r => r.n), ...run.filter(r => !r.early).map(r => r.n));
                    i = j;
                }
                if (out.some((n, k) => n !== nodes[k])) {
                    container.removeAll();
                    container.append(out);
                }
            };
            reorder(generated);
            root.append(generated.nodes);
        }
    };
}
orderTiesLikeTheCdn.postcss = true;

/** Adds the CDN's prefixes to the nodes after the marker only (the custom CSS stays as written). */
function autoprefixTailwindOutput() {
    const prefixes = new Prefixes(cdnPrefixes, new Browsers(agents, CDN_PREFIX_TARGETS, {}, {}), { remove: false });
    return {
        postcssPlugin: 'autoprefix-tailwind-output',
        OnceExit(root, { result, postcss }) {
            const generated = generatedNodes(root, postcss);
            if (!generated) return;
            prefixes.processor.add(generated, result);
            root.append(generated.nodes);
        }
    };
}
autoprefixTailwindOutput.postcss = true;

export default {
    plugins: [tailwindcss(), orderTiesLikeTheCdn(), autoprefixTailwindOutput()]
};
